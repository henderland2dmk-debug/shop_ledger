import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../core/customer_keys.dart';
import '../core/formatters.dart';
import '../models/sale.dart';

/// Builds the printable/downloadable bill for a completed or draft sale.
Future<Uint8List> buildBillPdf(Sale sale) async {
  final document = pw.Document(
    title: '${sale.id}.pdf',
    author: 'Mano Agency',
    subject: 'Sale bill ${sale.id}',
  );

  pw.ImageProvider? logo;
  try {
    logo = await imageFromAssetBundle('assets/logo/mano-agency-logo.jpeg');
  } catch (_) {
    // The bill is still useful when the logo asset is unavailable.
  }

  final rows = <List<String>>[];
  for (var index = 0; index < sale.items.length; index++) {
    final item = sale.items[index];
    rows.add([
      '${index + 1}',
      item.particulars,
      _money(item.rate),
      formatQuantity(item.quantity),
      _money(item.total),
    ]);
  }

  document.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(34),
      header: (context) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Row(
            children: [
              if (logo != null) pw.Image(logo, width: 46, height: 46),
              if (logo != null) pw.SizedBox(width: 12),
              pw.Expanded(
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      'MANO AGENCY',
                      style: pw.TextStyle(
                        fontSize: 20,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColor.fromHex('#13452C'),
                      ),
                    ),
                    pw.SizedBox(height: 2),
                    pw.Text(
                      'Inventory & billing',
                      style: const pw.TextStyle(
                        fontSize: 9,
                        color: PdfColors.grey700,
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ),
          pw.SizedBox(height: 14),
          pw.Divider(color: PdfColor.fromHex('#1F6B45'), thickness: 1.4),
        ],
      ),
      footer: (context) => pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            'Generated by Mano Agency',
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
          ),
          pw.Text(
            'Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
          ),
        ],
      ),
      build: (context) => [
        pw.SizedBox(height: 6),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  'SALE BILL',
                  style: pw.TextStyle(
                    fontSize: 23,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColor.fromHex('#13452C'),
                  ),
                ),
                pw.SizedBox(height: 6),
                pw.Text('Bill no: ${sale.id}'),
                pw.Text('Date: ${formatDateTime(sale.soldAt)}'),
              ],
            ),
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.end,
              children: [
                pw.Text(
                  'BILL TO',
                  style: pw.TextStyle(
                    fontSize: 9,
                    fontWeight: pw.FontWeight.bold,
                    color: PdfColors.grey700,
                  ),
                ),
                pw.SizedBox(height: 5),
                pw.Text(
                  sale.customerName.trim().isEmpty
                      ? walkInCustomer
                      : sale.customerName.trim(),
                  style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                ),
              ],
            ),
          ],
        ),
        pw.SizedBox(height: 22),
        pw.TableHelper.fromTextArray(
          context: context,
          headers: const ['#', 'Particulars', 'Rate', 'Qty', 'Total'],
          data: rows,
          headerStyle: pw.TextStyle(
            fontWeight: pw.FontWeight.bold,
            color: PdfColors.white,
            fontSize: 10,
          ),
          headerDecoration: pw.BoxDecoration(
            color: PdfColor.fromHex('#1F6B45'),
          ),
          cellStyle: const pw.TextStyle(fontSize: 10),
          cellHeight: 26,
          headerHeight: 28,
          cellPadding: const pw.EdgeInsets.symmetric(
            horizontal: 8,
            vertical: 4,
          ),
          cellAlignment: pw.Alignment.centerRight,
          cellAlignments: {0: pw.Alignment.center, 1: pw.Alignment.centerLeft},
          columnWidths: const {
            0: pw.FixedColumnWidth(30),
            1: pw.FlexColumnWidth(4),
            2: pw.FixedColumnWidth(78),
            3: pw.FixedColumnWidth(50),
            4: pw.FixedColumnWidth(90),
          },
          border: pw.TableBorder.all(
            color: PdfColor.fromHex('#D8E2D4'),
            width: 0.6,
          ),
        ),
        pw.SizedBox(height: 16),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.end,
          children: [
            pw.Container(
              width: 230,
              padding: const pw.EdgeInsets.all(12),
              decoration: pw.BoxDecoration(
                color: PdfColor.fromHex('#EDF5E8'),
                border: pw.Border.all(color: PdfColor.fromHex('#CDDFC3')),
              ),
              child: pw.Column(
                children: [
                  pw.Row(
                    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                    children: [
                      pw.Text('Total units'),
                      pw.Text(formatQuantity(sale.totalQuantity)),
                    ],
                  ),
                  pw.SizedBox(height: 8),
                  pw.Row(
                    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                    children: [
                      pw.Text(
                        'GRAND TOTAL',
                        style: pw.TextStyle(fontWeight: pw.FontWeight.bold),
                      ),
                      pw.Text(
                        _money(sale.totalAmount),
                        style: pw.TextStyle(
                          fontWeight: pw.FontWeight.bold,
                          fontSize: 13,
                          color: PdfColor.fromHex('#13452C'),
                        ),
                      ),
                    ],
                  ),
                ],
              ),
            ),
          ],
        ),
        pw.SizedBox(height: 26),
        pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text(
              '........................................',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
            ),
            pw.Text(
              'Shopkeeper signature',
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600),
            ),
          ],
        ),
      ],
    ),
  );

  return document.save();
}

String _money(num value) => 'Rs. ${formatPlainMoney(value)}';
